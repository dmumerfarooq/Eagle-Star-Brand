export function formatCurrency(amount: number, currency: 'AED' | 'PKR', lang: Language = 'en'): string {
  const formattedNumber = new Intl.NumberFormat(lang === 'ur' ? 'ur-PK' : 'en-US', {
    maximumFractionDigits: 2,
    minimumFractionDigits: 0
  }).format(amount);

  if (lang === 'ur') {
    return currency === 'AED' ? `${formattedNumber} درہم` : `${formattedNumber} روپے`;
  }
  return currency === 'AED' ? `AED ${formattedNumber}` : `PKR ${formattedNumber}`;
}

export function formatNumber(num: number, lang: Language = 'en'): string {
  return new Intl.NumberFormat(lang === 'ur' ? 'ur-PK' : 'en-US').format(num);
}
